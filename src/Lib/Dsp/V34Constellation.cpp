std::pair<int, int> RotateClockwise90(std::pair<int, int> point) { return {point.second, -point.first}; }

std::vector<std::pair<int, int>> BuildConstellation(int pointCount) {
    if (pointCount <= 0 || pointCount % 4 != 0 || pointCount > 1664) {
        throw std::invalid_argument("BuildConstellation: pointCount must be a positive multiple of 4, <= 1664");
    }
    const int quarterCount = pointCount / 4;
    std::vector<std::pair<int, int>> points;
    points.reserve(static_cast<size_t>(pointCount));
    for (int i = 0; i < quarterCount; ++i) {
        points.push_back(kQuarterConstellation[static_cast<size_t>(i)]);
    }
    // Apply successive clockwise rotations to the ORIGINAL quarter
    // points (90, then 180 = 90+90, then 270 = 90+90+90), not to
    // whatever was appended last, per 9.1's own wording ("rotations of
    // these signal points", i.e. of the quarter points themselves).
    for (int i = 0; i < quarterCount; ++i) {
        points.push_back(RotateClockwise90(kQuarterConstellation[static_cast<size_t>(i)]));
    }
    for (int i = 0; i < quarterCount; ++i) {
        points.push_back(RotateClockwise90(RotateClockwise90(kQuarterConstellation[static_cast<size_t>(i)])));
    }
    for (int i = 0; i < quarterCount; ++i) {
        points.push_back(
            RotateClockwise90(RotateClockwise90(RotateClockwise90(kQuarterConstellation[static_cast<size_t>(i)]))));
    }
    return points;
}

